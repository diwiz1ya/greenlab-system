const RU_TRANSLIT_HINT_RE = /\b(?:razbivka|zakaza|tip belya|smeshann|belye|tsvetn|temn|delikatn|sostav|veshch|obshch|problemn|sdelat|dobavit|sokhranit|zakryt|korzina|korziny|zapolnite|nizhnee|verkh|niz|noski|pyatno|sht)\b/i;

function containsRuText(value) {
  const text = String(value || "");
  return /[А-Яа-яЁё]/.test(text) || RU_TRANSLIT_HINT_RE.test(text);
}

export function translateRuToEnText(value) {
  if (!containsRuText(value)) return value;

  let text = String(value || "");
  for (const [pattern, replacement] of PHRASE_REPLACEMENTS) {
    text = text.replace(pattern, replacement);
  }

  text = text
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([,.;:!?])/g, "$1")
    .trim();

  return text;
}

export function deepTranslateRuToEn(value) {
  if (typeof value === "string") {
    return translateRuToEnText(value);
  }
  if (Array.isArray(value)) {
    return value.map((entry) => deepTranslateRuToEn(entry));
  }
  if (!value || typeof value !== "object") {
    return value;
  }

  const result = {};
  for (const [key, entry] of Object.entries(value)) {
    result[key] = deepTranslateRuToEn(entry);
  }
  return result;
}

function localizeNodeText(node) {
  if (!node || !containsRuText(node.nodeValue)) return;
  node.nodeValue = translateRuToEnText(node.nodeValue);
}

function localizeElementAttributes(element) {
  const attrs = ["placeholder", "title", "aria-label"];
  for (const attr of attrs) {
    const raw = element.getAttribute(attr);
    if (!containsRuText(raw)) continue;
    element.setAttribute(attr, translateRuToEnText(raw));
  }
}

let observerStarted = false;
let isLocalizingDom = false;

export function localizeDom(root) {
  if (!root || isLocalizingDom) return;

  isLocalizingDom = true;
  try {
    if (root.nodeType === Node.TEXT_NODE) {
      localizeNodeText(root);
      return;
    }

    if (root.nodeType === Node.ELEMENT_NODE) {
      localizeElementAttributes(root);
    }

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    let current = walker.nextNode();
    while (current) {
      if (current.nodeType === Node.TEXT_NODE) {
        localizeNodeText(current);
      } else if (current.nodeType === Node.ELEMENT_NODE) {
        localizeElementAttributes(current);
      }
      current = walker.nextNode();
    }
  } finally {
    isLocalizingDom = false;
  }
}

export function startAutoLocalize(root) {
  if (!root || observerStarted) return;
  observerStarted = true;

  const observer = new MutationObserver((mutations) => {
    if (isLocalizingDom) return;
    for (const mutation of mutations) {
      if (mutation.type === "characterData") {
        localizeDom(mutation.target);
        continue;
      }

      if (mutation.type === "attributes" && mutation.target) {
        localizeDom(mutation.target);
      }

      for (const node of mutation.addedNodes) {
        localizeDom(node);
      }
    }
  });

  observer.observe(root, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: ["placeholder", "title", "aria-label"]
  });
}
